"""Forces, relaxations and restarts of a bulk cell at the Gamma point on the Fortran-derived routines in the sectors of
its point group (``PARSEC_FORTRAN_SECTOR_FORCES``).

The parser hands a Gamma-point forces or relaxation input to the Fortran-derived routines (``Use_Fortran_Routines``)
for many reasons: the input asks for them, every species is ``Cubic_Spline`` (``GAMMA_FORCES_FEATURE``), an FHI
pseudopotential, a core correction, another mixer or eigensolver, a double grid (and ``Restart_Run`` under
``PARSEC_FILE_KEYWORD_ROUTINES=fortran``; under the default ``neutral`` a restart keeps the routines of the run that
wrote its file).  Under ``auto`` (the default) their forces keep the sectors of the point group of the cell: the local
terms of those routines read the fields the sectors expand to the full grid, the nonlocal term is contracted in the
sectors with the gradients of the projectors with their lattice images and completed over the group of the sectors,
and the total is averaged over the group generated by the operations of those routines and of the sectors.  The
forces, energies and moves must be those of the full grid (``off``, as before) to the criterion of the SCF.
"""

