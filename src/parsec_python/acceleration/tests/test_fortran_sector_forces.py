class OperationGroupTests(unittest.TestCase):
    """The group of the operations of the routines and of the sectors (:func:`fortran_force_operations`)."""

    @staticmethod
    def _cell():
        from parsec_python.models import Atom

        side = 6.0
        lattice = np.eye(3) * side
        # a CsCl-like cell of two species with a third atom: the body-centring translation maps A onto A only where
        # the cell holds two A atoms, so build one with the translation (1/2, 1/2, 1/2) and a cubic point group
        atoms = (
            Atom("A", np.array([0.0, 0.0, 0.0])),
            Atom("A", np.array([3.0, 3.0, 3.0])),
            Atom("B", np.array([3.0, 0.0, 0.0])),
            Atom("B", np.array([0.0, 3.0, 3.0])),
        )
        return atoms, lattice

    def test_containment_returns_the_larger_set_unchanged_and_the_generated_group_otherwise(self) -> None:
        from parsec_python.acceleration.Forces.sector_symmetry import fortran_force_operations
        from parsec_python.Forces.periodic import PeriodicAtomSymmetryOperation, periodic_symmetry_operations
        from parsec_python.Forces.symmetry import symmetrize_forces, symmetrize_positions

        atoms, lattice = self._cell()
        point = periodic_symmetry_operations(atoms, lattice)
        self.assertGreater(len(point), 1)
        subgroup = point[:1]
        self.assertIs(fortran_force_operations(point, subgroup), point)
        self.assertIs(fortran_force_operations(subgroup, point), point)
        self.assertIs(fortran_force_operations(point, None), point)
        self.assertIs(fortran_force_operations((), point), point)
        # the body-centring translation alone (with the identity) against the point group about the origin
        translation = PeriodicAtomSymmetryOperation(
            matrix=np.eye(3), image=np.array([1, 0, 3, 2]), lattice_vectors=lattice, translation=np.array([3.0] * 3)
        )
        generated = fortran_force_operations(point, (point[0], translation))
        self.assertEqual(len(generated), 2 * len(point))
        self.assertIs(generated[0], point[0])
        keys = {(tuple(np.round(op.matrix, 9).ravel()), tuple(op.image)) for op in generated}
        self.assertEqual(len(keys), len(generated))
        positions = np.array([atom.position for atom in atoms])
        np.testing.assert_allclose(symmetrize_positions(positions, generated), positions, rtol=0, atol=1e-12)
        # a vector field that the group fixes stays; one it does not is projected
        forces = np.arange(12.0).reshape(4, 3)
        averaged = symmetrize_forces(forces, generated)
        np.testing.assert_allclose(symmetrize_forces(averaged, generated), averaged, rtol=0, atol=1e-12)


def _loop_operations(atoms, lattice, grid=None, tolerance=1.0e-6):
    """The search of :func:`parsec_python.Forces.periodic.periodic_symmetry_operations` before 2026-11-19 (every pair of
    atoms per operation), as ``(matrix, image)`` pairs."""

    from parsec_python.Forces.periodic import _grid_invariant, _lattice_point_operations
    from parsec_python.Grid.cell import fractional_coordinates

    vectors = np.asarray(lattice, dtype=float)
    positions = np.array([atom.position for atom in atoms], dtype=np.float64)
    symbols = [atom.symbol for atom in atoms]
    fractions = fractional_coordinates(positions, vectors)
    found = []
    for rotation, matrix in _lattice_point_operations(vectors):
        if grid is not None and not _grid_invariant(grid, matrix):
            continue
        mapped = fractions @ matrix
        image = np.full(len(atoms), -1, dtype=np.int64)
        valid = True
        for index, point in enumerate(mapped):
            difference = point[None, :] - fractions
            difference -= np.round(difference)
            distance = np.linalg.norm(difference @ vectors, axis=1)
            candidates = [other for other in np.flatnonzero(distance <= tolerance) if symbols[other] == symbols[index]]
            if len(candidates) != 1:
                valid = False
                break
            image[index] = candidates[0]
        if not valid or np.unique(image).size != len(atoms):
            continue
        found.append((rotation, image))
    return found


class PointOperationSearchTests(unittest.TestCase):
    """The tree search of the point operations of a cell gives the operations of the loop over every pair."""

    def _check(self, atoms, lattice, tolerance=1.0e-6) -> int:
        from parsec_python.Forces.periodic import periodic_symmetry_operations

        expected = _loop_operations(atoms, lattice, tolerance=tolerance)
        found = periodic_symmetry_operations(atoms, lattice, tolerance=tolerance)
        self.assertEqual(len(found), len(expected))
        for operation, (rotation, image) in zip(found, expected):
            np.testing.assert_array_equal(operation.matrix, rotation)
            np.testing.assert_array_equal(operation.image, image)
        return len(found)

    def test_structures(self) -> None:
        from parsec_python.models import Atom

        side = 10.26
        lattice = np.eye(3) * side
        diamond = displaced_positions(0.0)
        # the diamond cube, the displaced cube (Td), with the origin atom moved (C2v), an atom of another species,
        # atoms on the faces of the cell (fractions 0 and 1 within round-off) and a tetragonal cell
        cases = [
            [Atom("Si", p) for p in diamond],
            [Atom("Si", p) for p in displaced_positions()],
            [Atom("Si", p) for p in displaced_positions(origin_shift=0.05)],
            [Atom("C" if index == 4 else "Si", p) for index, p in enumerate(diamond)],
            [Atom("Si", p + (np.array([side, -side, 0.0]) if index == 1 else 0.0) - 1e-15)
             for index, p in enumerate(diamond)],
        ]
        counts = [self._check(atoms, lattice) for atoms in cases]
        self.assertEqual(counts[:3], [24, 24, 4])
        tetragonal = np.diag([10.26, 10.26, 12.0])
        self._check([Atom("Si", p * np.array([1.0, 1.0, 12.0 / 10.26])) for p in diamond], tetragonal)
        # two atoms within the tolerance of one another: two candidates, not even the identity (both searches)
        from parsec_python.Forces.periodic import periodic_symmetry_operations

        crowded = [Atom("Si", np.array([1.0, 2.0, 3.0])), Atom("Si", np.array([1.0, 2.0, 3.0 + 5e-7])),
                   Atom("Si", np.array([4.0, 4.0, 4.0]))]
        self.assertEqual(_loop_operations(crowded, lattice), [])
        with self.assertRaises(RuntimeError):
            periodic_symmetry_operations(crowded, lattice)
        # a large tolerance: several candidates
        self._check([Atom("Si", p) for p in displaced_positions()], lattice, tolerance=0.1)


class GradientSelectionTests(unittest.TestCase):
    """The projector gradients of selected atoms are the columns of those of every atom, bit for bit."""

    def _check(self, double_grid_order: int) -> None:
        from parsec_python.Forces.periodic import build_periodic_projector_gradients
        from parsec_python.Grid.pbc import PeriodicCell, PeriodicGridSettings, build_periodic_grid
        from parsec_python.Input.parsec_input import parse_parsec_input
        from parsec_python.SCF.pbc import load_pseudopotentials

        with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as name:
            path = write_silicon(Path(name), FORTRAN, settings={**SILICON_SETTINGS, "Grid_Spacing": "0.8"})
            problem = parse_parsec_input(path).problem
            potentials = load_pseudopotentials(problem.pseudopotentials, xc_functional=problem.scf.xc_functional)
        settings = problem.grid
        if double_grid_order > 1:
            from dataclasses import replace

            settings = replace(settings, double_grid_order=double_grid_order)
        grid = build_periodic_grid(problem.periodic_cell, settings)
        lattice = np.asarray(problem.periodic_cell.lattice_vectors)
        whole = build_periodic_projector_gradients(grid, problem.atoms, potentials, problem.pseudopotentials, lattice)
        selected = [0, 5]
        part = build_periodic_projector_gradients(
            grid, problem.atoms, potentials, problem.pseudopotentials, lattice, atom_indices=selected
        )
        columns = [index for index, label in enumerate(whole.labels) if label[0] in selected]
        self.assertTrue(columns)
        self.assertEqual(part.labels, tuple(whole.labels[index] for index in columns))
        np.testing.assert_array_equal(part.signs, whole.signs[columns])
        for axis in range(3):
            expected = whole.components[axis][:, columns].tocsc()
            found = part.components[axis].tocsc()
            expected.sort_indices()
            found.sort_indices()
            np.testing.assert_array_equal(found.indptr, expected.indptr)
            np.testing.assert_array_equal(found.indices, expected.indices)
            np.testing.assert_array_equal(found.data, expected.data)
        with self.assertRaises(ValueError):
            build_periodic_projector_gradients(
                grid, problem.atoms, potentials, problem.pseudopotentials, lattice, atom_indices=[8]
            )

    def test_plain_grid(self) -> None:
        self._check(1)

    def test_double_grid(self) -> None:
        self._check(2)


@unittest.skipUnless(cupy_available() and native_available(), "CUDA runtime or native extension is unavailable")
class FortranSectorForceTests(unittest.TestCase):
    """The forces of the displaced silicon cube on the Fortran-derived routines, in the sectors and on the full grid,
    for the triggers of those routines."""

    @classmethod
    def setUpClass(cls) -> None:
        cls._directory = tempfile.TemporaryDirectory(ignore_cleanup_errors=True)
        cls.root = Path(cls._directory.name)
        cls.runs = {}
        for label, extra in (("fortran", FORTRAN + FORCES), ("spline", SPLINE + FORCES)):
            for setting in ("off", "auto"):
                cls.runs[label, setting] = _silicon(cls.root / f"{label}_{setting}", extra, setting)

    @classmethod
    def tearDownClass(cls) -> None:
        cls._directory.cleanup()

    def _compare(self, label: str) -> None:
        for setting in ("off", "auto"):
            status, _, log, errors = self.runs[label, setting]
            self.assertEqual(status, 0, f"{label} {setting}: {errors}\n{log[-3000:]}")
            self.assertIn("Fortran-derived", log)
        _, full, full_log, _ = self.runs[label, "off"]
        _, sectors, sector_log, _ = self.runs[label, "auto"]
        self.assertNotIn("Forces of the periodic cell in the sectors", full_log)
        self.assertIn("Forces of the periodic cell in the sectors of its point group: averaged over 24 operations",
                      sector_log)
        # Td about the origin: the operations of the routines are those of the sectors
        self.assertIn("Forces of the Fortran-derived routines in the sectors: their own terms, the total and the moved "
                      "positions averaged over 24 operations (the group of their 24 and of the 24 of the sectors",
                      sector_log)
        self.assertNotIn("Forces of the Fortran-derived routines", full_log)
        self.assertGreater(float(np.abs(full["forces_total"]).max()), 1.0e-3)
        np.testing.assert_allclose(sectors["forces_total"], full["forces_total"], rtol=0, atol=2e-6)
        self.assertAlmostEqual(float(sectors["energy_total_ry"]), float(full["energy_total_ry"]), delta=1e-7)

    def test_use_fortran_routines(self) -> None:
        self._compare("fortran")

    def test_the_local_terms_of_the_orbits_are_those_of_every_atom(self) -> None:
        # the same SCF in the sectors, the local terms summed for every atom (the switches of the default routines)
        for label, positions, environment in (
            ("every_atom", None, {"PARSEC_PERIODIC_SECTOR_LOCAL_FORCES": "all"}),
            ("abelian_every_atom", displaced_positions(origin_shift=0.05), {"PARSEC_PERIODIC_LOCAL_ORBITS": "off"}),
            ("abelian_orbits", displaced_positions(origin_shift=0.05), None),
        ):
            self.runs[label, "auto"] = _silicon(
                self.root / label, FORTRAN + FORCES, "auto", positions=positions, environment=environment
            )
